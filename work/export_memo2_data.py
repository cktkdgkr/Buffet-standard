"""
Payload for the second round of memo replies.

Each reply carries three things so the mapping is never ambiguous: where in the
previous document the memo sits, the sentence it was attached to, and the memo
text itself - then the analysis.

Figures come from work/alphabet_memo2.json and work/analysis.json rather than
being typed in, so the prose cannot drift from the computation.

Writes work/_memo2_payload.json for export_memo_docx.js.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name):
    with open(os.path.join(HERE, name)) as fh:
        return json.load(fh)


