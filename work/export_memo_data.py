def pct(x, d=1):
    return "-" if x is None else f"{x*100:.{d}f}%"


def bn(x, d=1):
    """Dollars in billions, with the minus outside the sign so "$-7.5B" never appears."""
    if x is None:
        return "-"
    return f"{'−' if x < 0 else ''}${abs(x)/1e9:,.{d}f}B"


def x(v, d=2):
    return "-" if v is None else f"{v:.{d}f}x"


blocks = []


def h1(t):
    blocks.append({"t": "h1", "text": t})


def h2(t):
    blocks.append({"t": "h2", "text": t})


def h3(t):
    blocks.append({"t": "h3", "text": t})


def p(t):
    blocks.append({"t": "p", "text": t})


def note(t):
    blocks.append({"t": "note", "text": t})


def quote(t, src):
    blocks.append({"t": "quote", "text": t, "src": src})


def bullets(items):
    blocks.append({"t": "bullets", "items": items})


def table(headers, rows, widths, numeric=()):
    blocks.append({"t": "table", "headers": headers,
                   "rows": [[str(c) for c in r] for r in rows],
                   "widths": widths, "numeric": list(numeric)})


def memo(n, anchor, question):
    blocks.append({"t": "memo", "n": n, "anchor": anchor, "question": question})


