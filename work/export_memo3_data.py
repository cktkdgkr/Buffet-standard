def pct(v, d=1):
    """Percentages, with the same minus sign the amounts use."""
    if v is None:
        return "-"
    return f"{'−' if v < 0 else ''}{abs(v)*100:.{d}f}%"


def bn(v, d=1):
    """Figures arrive in millions of dollars; the report reads in billions."""
    if v is None:
        return "-"
    return f"{'−' if v < 0 else ''}${abs(v)/1e3:,.{d}f}B"


def bn9(v, d=1):
    if v is None:
        return "-"
    return f"{'−' if v < 0 else ''}${abs(v)/1e9:,.{d}f}B"


def usd(v, d=0):
    return "-" if v is None else f"${v:,.{d}f}"


def x(v, d=1):
    return "-" if v is None else f"{v:.{d}f}배"


